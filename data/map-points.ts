const label = (name: string): PointLabel => {
  const nameZh = zh[name];
  if (!nameZh) throw new Error(`Missing bilingual map label: ${name}`);
  return {
    nameZh,
    nameEn: official[name] || name,
    address: addresses[name],
  };
};

